def catalog_for(version):
    """Read the named catalogue; historical preparations never inherit new data."""
    if not isinstance(version, str) or version not in CATALOGS:
        raise ValueError("Version du catalogue Petits hommes inconnue.")
    return CATALOGS[version]


def normalize_object_name(name):
    """Normalize typography only; do not infer objects from prose or adjectives."""
    if not isinstance(name, str):
        return ""
    value = "".join(character for character in unicodedata.normalize("NFKD", name.casefold())
                    if not unicodedata.combining(character))
    return " ".join(re.sub(r"[\W_]+", " ", value).split())


